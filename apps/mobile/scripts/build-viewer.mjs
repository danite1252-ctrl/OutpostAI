// Bundles viewer/viewer.js (three.js and its loaders) into one HTML page, written to
// src/viewer-html.ts for the WebView. Runs after `npm install` (postinstall).

import { build } from "esbuild";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = await build({
  entryPoints: [join(root, "viewer", "viewer.js")],
  bundle: true,
  minify: true,
  format: "iife",
  target: "chrome90",
  write: false,
  legalComments: "none",
});
const js = out.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const html =
  '<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no">' +
  "<style>html,body{margin:0;height:100%;overflow:hidden;background:#1b181c;touch-action:none}canvas{display:block}</style></head><body>" +
  `<script>${js}</script></body></html>`;
writeFileSync(
  join(root, "src", "viewer-html.ts"),
  "// Generated by scripts/build-viewer.mjs from viewer/viewer.js (three.js, MIT). Don't edit.\n" +
    `export const VIEWER_HTML: string = ${JSON.stringify(html)};\n`,
);
console.log(`viewer: ${Math.round(html.length / 1024)} KB`);
